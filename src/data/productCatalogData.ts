// LocalStorage helpers for persistent customer reservations
const RESERVATIONS_STORAGE_KEY = 'the_shop_customer_reservations';

export function getStoredReservations(): ReservedProduct[] {
  try {
    const raw = localStorage.getItem(RESERVATIONS_STORAGE_KEY);
    if (raw) return JSON.parse(raw);
  } catch {
    // fallback
  }
  return [
    {
      reservationId: 'res-sample-1',
      productId: 'prod-a-iphone',
      productName: 'Apple iPhones (Pro Max Series)',
      imageUrl: 'https://images.unsplash.com/photo-1592750475338-74b7b21085ab?auto=format&fit=crop&w=800&q=80',
      category: 'Electronics',
      lockedPrice: 1099,
      originalPrice: 1299,
      reservedAt: 'Oct 2, 2026',
      targetBuyDate: 'Oct 28, 2026 (Next Paycheck)',
      notes: 'Locked $200 discount for 30 days.',
      status: 'active'
    }
  ];
}

export function saveReservation(reservation: ReservedProduct): ReservedProduct[] {
  const current = getStoredReservations();
  const updated = [reservation, ...current.filter(r => r.reservationId !== reservation.reservationId)];
  try {
    localStorage.setItem(RESERVATIONS_STORAGE_KEY, JSON.stringify(updated));
  } catch {
    // fallback
  }
  return updated;
}

export function cancelReservation(reservationId: string): ReservedProduct[] {
  const current = getStoredReservations();
  const updated = current.filter(r => r.reservationId !== reservationId);
  try {
    localStorage.setItem(RESERVATIONS_STORAGE_KEY, JSON.stringify(updated));
  } catch {
    // fallback
  }
  return updated;
}
