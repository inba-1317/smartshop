// Generates 5 distinct historical price change points ending at currentPrice
export function generate5PriceChanges(basePrice: number, itemName: string): PriceChangePoint[] {
  const factor = (itemName.charCodeAt(0) % 7) - 3;
  const p1 = Math.round(basePrice * 1.25 + factor);
  const p2 = Math.round(basePrice * 1.38 + (factor * 2));
  const p3 = Math.round(basePrice * 1.12 - factor);
  const p4 = Math.round(basePrice * 1.20 + factor);
  const p5 = basePrice;

  return [
    {
      period: 'May 2026',
      date: 'May 14, 2026',
      price: p1,
      label: 'Initial Launch Price',
      note: 'Original catalog retail benchmark'
    },
    {
      period: 'Jun 2026',
      date: 'Jun 22, 2026',
      price: p2,
      label: 'Peak Seasonal Demand',
      note: 'Supply constraint & high seasonal index'
    },
    {
      period: 'Jul 2026',
      date: 'Jul 30, 2026',
      price: p3,
      label: 'Mid-Year Flash Promo',
      note: 'Special 72-hour promotional markdown'
    },
    {
      period: 'Aug 2026',
      date: 'Aug 25, 2026',
      price: p4,
      label: 'Inventory Restock',
      note: 'Wholesale batch adjustment'
    },
    {
      period: 'Oct 2026 (Current)',
      date: 'Today',
      price: p5,
      label: 'SmartShop Verified Price',
      note: 'Current consumer-optimized benchmark price'
    }
  ];
}

